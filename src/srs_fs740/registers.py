from enum import IntFlag
from typing import TypeVar

T = TypeVar("T", bound=IntFlag)


class ESR(IntFlag):
    # Define each bit with its corresponding value.
    # Bits 1 and 6 are reserved, so you may choose to omit or mark them as Reserved.
    OPC = 1 << 0  # Operation Complete
    QYE = 1 << 2  # Query Error
    DDE = 1 << 3  # Device-Dependent Error
    EXE = 1 << 4  # Execution Error
    CME = 1 << 5  # Command Error
    PON = 1 << 7  # Power On


class SerialPollStatus(IntFlag):
    """Serial Poll Status Byte (STB) as defined on page 82.

    Bit definitions:
      - Bit 0: Reserved
      - Bit 1: GPS status unmasked bit set.
      - Bit 2: Error queue is not empty
      - Bit 3: Questionable status register unmasked bit set.
      - Bit 4: Interface oubut buffer has at least one character.
      - Bit 5: ESR status register unmasked bit set.
      - Bit 6: Master summary bit.
      - Bit 7: OPER status register unmasked bit set.
    """

    GPS = 1 << 1
    ERR = 1 << 2
    QUES = 1 << 3
    MAV = 1 << 4
    ESR = 1 << 5
    MSS = 1 << 6
    OPER = 1 << 7


class QuestionableStatus(IntFlag):
    """Questionable Status Register as defined on page 85.

    Bit definitions:
      - Bit 0: Time-of-day not set by the GPS receiver (time information invalid)
      - Bit 1: Timebase is still warming up
      - Bit 2: Timebase is not locked to GPS (time unlock)
      - Bit 3: Reserved (or defined as needed)
      - Bit 4: Reserved (or defined as needed)
      - Bit 5: Frequency stability not yet achieved (timebase stability not optimum)
      - Bits 6-9: Reserved (or defined as needed)
      - Bit 10: Rb timebase unlocked, frequency not stable
      - Bit 11: PLL circuit has come unlocked.
      - Bit 12: TCXO frequency control near rail
      - Bit 13: Frequency control for installed timebase saturated
    """

    TOD_NOT_SET = 1 << 0
    WARM_UP = 1 << 1
    TIME_UNLOCK = 1 << 2
    FREQ_UNSTABLE = 1 << 5
    RB_UNLOCK = 1 << 10
    PLL_UNLOCK = 1 << 11
    EFC_10MHz = 1 << 12
    EFC_GPS = 1 << 13


class OperationStatus(IntFlag):
    """Operation Status Register as defined on page 86.

    Bit definitions:
      - Bit 0: Reserved
      - Bit 1: Hardware settings are changing (setting change in progress)
      - Bits 2-3: Reserved
      - Bit 4: Measurement on front input in progress
      - Bit 5: Measurement on rear input in progress
      - Bit 6: Timing event detected on front input
      - Bit 7: Timing event detected on back input
    """

    SETTING_CHANGE = 1 << 1
    MEASURE_FRONT = 1 << 4
    MEASURE_REAR = 1 << 5
    EVENT_FRONT = 1 << 6
    EVENT_REAR = 1 << 7


class GPSReceiverStatus(IntFlag):
    """GPS Receiver Status Register – see Table 12 on page 87 of the FS740 manual.

    Bit definitions:
      - Bit 0: TIME_NOT_SET – Time-of-day information has not been received from the satellites.
      - Bit 1: ANTENNA_OPEN – The GPS antenna does not appear to be connected to the receiver input.
      - Bit 2: ANTENNA_SHORT – The receiver input appears to be shorted.
      - Bit 3: NO_SATELLITES – No GPS satellites have been found.
      - Bit 4: UTC_UNKNOWN – The UTC offset from GPS is unknown.
      - Bit 5: SURVEY_IN_PROGRESS – A position survey is in progress.
      - Bit 6: NO_POSITION_STORED – No surveyed position has been stored in nonvolatile memory.
      - Bit 7: LEAP_SECOND_PENDING – A leap second is pending (usually scheduled for end of day on June 30 or December 31).
      - Bit 8: RESERVED_8 – No definition provided.
      - Bit 9: POSITION_QUESTIONABLE – The stored position appears to be incorrect; a new survey may be needed.
      - Bit 10: RESERVED_10 – No definition provided.
      - Bit 11: ALMANAC_INCOMPLETE – A complete almanac has not been downloaded from the satellites.
      - Bit 12: NO_TIMING_PULSES – Timing pulses are not being generated by the receiver.
      - Bits 13–15: RESERVED – No definitions provided.
    """

    TIME_NOT_SET = 1 << 0
    ANTENNA_OPEN = 1 << 1
    ANTENNA_SHORT = 1 << 2
    NO_SATELLITES = 1 << 3
    UTC_UNKNOWN = 1 << 4
    SURVEY_IN_PROGRESS = 1 << 5
    NO_POSITION_STORED = 1 << 6
    LEAP_SECOND_PENDING = 1 << 7
    RESERVED_8 = 1 << 8
    POSITION_QUESTIONABLE = 1 << 9
    RESERVED_10 = 1 << 10
    ALMANAC_INCOMPLETE = 1 << 11
    NO_TIMING_PULSES = 1 << 12
    RESERVED_13 = 1 << 13
    RESERVED_14 = 1 << 14
    RESERVED_15 = 1 << 15


def get_set_flags(register_value: int, register: T) -> list[T]:
    set_flags = [flag for flag in register & register_value]
    return set_flags
